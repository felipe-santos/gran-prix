#!/usr/bin/env node
/**
 * Embeds src/kernels.ts into src/kernelsSource.ts as a map name -> source text, so
 * the generator can paste the exact same numeric code into every generated module.
 *
 *   node scripts/embed-kernels.mjs           # (re)write src/kernelsSource.ts
 *   node scripts/embed-kernels.mjs --check   # exit 1 when it is out of date
 *
 * The file header is dropped and the `export ` keywords are removed; each
 * function is copied verbatim. See the header of src/kernels.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src', 'kernels.ts');
const OUT = join(root, 'src', 'kernelsSource.ts');

/** Pure function so the test can reuse the exact transformation. */
export function renderKernelsSource(kernelsTs) {
  const start = kernelsTs.indexOf('/** Decodes');
  if (start < 0) throw new Error('kernels.ts: marker "/** Decodes" not found');
  const body = kernelsTs.slice(start).replace(/^export /gm, '').trimEnd();
  const kernels = {};
  for (const chunk of body.split(/\n\n+/)) {
    const m = /^function (\w+)\(/m.exec(chunk);
    if (!m) throw new Error('kernels.ts: chunk without a top-level function:\n' + chunk);
    kernels[m[1]] = chunk + '\n';
  }
  return (
    '// GENERATED by scripts/embed-kernels.mjs from src/kernels.ts. Do not edit.\n' +
    '// Run `pnpm run embed` after changing src/kernels.ts.\n' +
    '/** Source text of each kernel, keyed by function name. */\n' +
    'export const KERNELS: Readonly<Record<string, string>> = ' +
    JSON.stringify(kernels, null, 2) +
    ';\n'
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rendered = renderKernelsSource(readFileSync(SRC, 'utf8'));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== rendered) {
      console.error('src/kernelsSource.ts is out of date: run `pnpm run embed`');
      process.exit(1);
    }
    console.log('src/kernelsSource.ts is up to date');
  } else {
    writeFileSync(OUT, rendered);
    console.log('wrote ' + OUT);
  }
}
