import { KERNELS } from './kernelsSource.js';
import { prepareModel, type ExportOptions, type PreparedModel } from './prepare.js';

export type { ExportOptions } from './prepare.js';

/** Statements of `forward()` for the network, with literal dims and offsets. */
function forwardBody(m: PreparedModel): string[] {
  const lines: string[] = ['let a: Float32Array = x;'];
  let owned = false;
  let linearIdx = 0;
  const own = (): void => {
    if (!owned) {
      lines.push('a = a.slice(); // never mutate the caller\'s input');
      owned = true;
    }
  };
  m.def.layers.forEach((layer, i) => {
    switch (layer.type) {
      case 'linear': {
        const wOff = m.layout[linearIdx * 2].offset;
        const bOff = m.layout[linearIdx * 2 + 1].offset;
        linearIdx++;
        lines.push(
          `a = linearKernel(W, a, n, ${layer.in_features}, ${layer.out_features}, ${wOff}, ${bOff}); // layers[${i}] linear`,
        );
        owned = true;
        break;
      }
      case 'activation': {
        own();
        const dim = layerOutputDim(m, i);
        if (layer.function === 'relu') lines.push(`reluInPlace(a); // layers[${i}]`);
        else if (layer.function === 'tanh') lines.push(`tanhInPlace(a); // layers[${i}]`);
        else if (layer.function === 'sigmoid') lines.push(`sigmoidInPlace(a); // layers[${i}]`);
        else lines.push(`softmaxRowsInPlace(a, n, ${dim}); // layers[${i}]`);
        break;
      }
      case 'dropout':
        lines.push(`// layers[${i}] dropout(${layer.rate}): identity at inference`);
        break;
      default:
        throw new Error('unreachable: unsupported layer survived parseNetworkDef');
    }
  });
  own();
  lines.push('return a;');
  return lines;
}

/** Output width after layer `i` (needed by a mid-network softmax). */
function layerOutputDim(m: PreparedModel, i: number): number {
  let dim = m.inputDim;
  for (let k = 0; k <= i; k++) {
    const l = m.def.layers[k];
    if (l.type === 'linear') dim = l.out_features;
  }
  return dim;
}

/** Kernels referenced by the generated code, in dependency-free order. */
function usedKernels(m: PreparedModel): string[] {
  const used = new Set<string>(['decodeWeights', 'checkInputs', 'linearKernel']);
  for (const l of m.def.layers) {
    if (l.type === 'activation') used.add(l.function === 'softmax' ? 'softmaxRowsInPlace' : `${l.function}InPlace`);
  }
  if (m.head === 'sigmoid') used.add('sigmoidInPlace');
  if (m.head === 'softmax') used.add('softmaxRowsInPlace');
  return Object.keys(KERNELS).filter((k) => used.has(k));
}

function headStatement(m: PreparedModel): string {
  if (m.head === 'sigmoid') return 'sigmoidInPlace(a);';
  if (m.head === 'softmax') return `softmaxRowsInPlace(a, n, ${m.outputDim});`;
  return '// head "none": probabilities are the raw outputs';
}

/**
 * Generates a self-contained, dependency-free TypeScript (ESM) module that
 * runs the forward pass of a trained gran-prix MLP.
 *
 * The output exports `predictLogits(input)`, `predictProbs(input)`,
 * `predictLogitsBatch(inputs, n)`, `predictBatch(inputs, n)` and the constants
 * `NETWORK_DEF_DIGEST`, `WEIGHTS_DIGEST`, `INPUT_DIM`, `OUTPUT_DIM`,
 * `PARAM_COUNT`, `HEAD`. Weights travel as a base64 f32 little-endian blob.
 * Generation is deterministic: the same inputs give the same text (no
 * timestamps).
 *
 * @param networkDefJson `NetworkDef` JSON, e.g. `trainer.networkDefJson()`.
 * @param weights flat weights in `export_flat` order, e.g. `trainer.get_weights()`.
 * @throws `UnsupportedLayerError` for batchnorm / rnn / gru / unknown layers;
 *         `Error` for malformed definitions or mismatching weights.
 */
export function generateInferenceModule(
  networkDefJson: string | unknown,
  weights: Float32Array | number[],
  opts: ExportOptions = {},
): string {
  const m = prepareModel(networkDefJson, weights, opts);
  const layers = m.def.layers.map((l) => {
    if (l.type === 'linear') return `linear(${l.in_features}->${l.out_features})`;
    if (l.type === 'activation') return l.function;
    return `${l.type}`;
  });

  const kernels = usedKernels(m)
    .map((name) => KERNELS[name])
    .join('\n');

  const body = forwardBody(m)
    .map((l) => '  ' + l)
    .join('\n');

  return `// GENERATED by @gran-prix/infer-ts. Do not edit; regenerate from the model package.
// Self-contained: no imports, no WASM, no eval (safe under strict page CSP).
// Architecture: ${m.inputDim} -> ${layers.join(' -> ')} (${m.paramCount} parameters)

/** sha256 of the canonical JSON (RFC 8785) of the NetworkDef. */
export const NETWORK_DEF_DIGEST = ${JSON.stringify(m.networkDefDigest)};
/** sha256 of the f32 little-endian weight bytes. */
export const WEIGHTS_DIGEST = ${JSON.stringify(m.weightsDigest)};
export const INPUT_DIM = ${m.inputDim};
export const OUTPUT_DIM = ${m.outputDim};
export const PARAM_COUNT = ${m.paramCount};
/** Output head applied by predictProbs / predictBatch. */
export const HEAD: 'sigmoid' | 'softmax' | 'none' = ${JSON.stringify(m.head)};

const WEIGHTS_B64 = ${JSON.stringify(m.weightsBase64)};

${kernels}
const W: Float32Array = decodeWeights(WEIGHTS_B64, PARAM_COUNT);

function forward(x: Float32Array, n: number): Float32Array {
${body}
}

/** Raw network output (logits) for one sample of INPUT_DIM features. */
export function predictLogits(input: Float32Array): Float32Array {
  return predictLogitsBatch(input, 1);
}

/** Raw network outputs for \`n\` row-major samples (n * OUTPUT_DIM values). */
export function predictLogitsBatch(inputs: Float32Array, n: number): Float32Array {
  checkInputs(inputs, n, INPUT_DIM, ${m.checkFinite});
  return forward(inputs, n);
}

/** Output head applied (HEAD) for one sample. */
export function predictProbs(input: Float32Array): Float32Array {
  return predictBatch(input, 1);
}

/** Output head applied (HEAD) for \`n\` row-major samples (n * OUTPUT_DIM values). */
export function predictBatch(inputs: Float32Array, n: number): Float32Array {
  checkInputs(inputs, n, INPUT_DIM, ${m.checkFinite});
  const a = forward(inputs, n);
  ${headStatement(m)}
  return a;
}
`;
}
