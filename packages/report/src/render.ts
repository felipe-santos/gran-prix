import type { EvalReport } from "@gran-prix/contracts";
import { comparisonSection } from "./compare.js";
import { parseExtras, type ReportExtras } from "./extras.js";
import { esc } from "./format.js";
import { calibrationSection, prSection } from "./sections-curves.js";
import { gatesSection, headerHtml } from "./sections-head.js";
import { confusionSection, strataSection } from "./sections-metrics.js";
import { downstreamSection, notesSection, tokensSection } from "./sections-tail.js";
import { CSS } from "./styles.js";
import { absent, type Ctx, type Section } from "./ui.js";

export interface RenderOptions {
  /** Data the EvalReport contract cannot carry yet (CIs, PR points, D1/D2, notes). Validated here. */
  extras?: ReportExtras;
  /** A second report to compare against (same dataset required for deltas). */
  compare?: EvalReport;
  /** Overrides the document <title>. */
  title?: string;
}

/**
 * Renders ONE self-contained HTML document: inline CSS and SVG, no scripts, fonts, images or
 * network references. Pure function of its inputs: no clock, no randomness, so the output is
 * byte-stable and can be diffed or attached to a decision record.
 *
 * The caller is expected to have validated `report` with `@gran-prix/contracts`; `extras` is
 * validated here and a malformed one throws `ExtrasError`.
 */
export function renderReport(report: EvalReport, opts: RenderOptions = {}): string {
  const ctx: Ctx = { r: report, x: opts.extras ? parseExtras(opts.extras) : {} };
  const sections: Section[] = [];
  const add = (s: Section | undefined): void => {
    if (s) sections.push(s);
  };
  add(gatesSection(ctx));
  add(strataSection(ctx));
  add(confusionSection(ctx));
  add(prSection(ctx));
  add(calibrationSection(ctx));
  add(tokensSection(ctx));
  add(downstreamSection(ctx));
  if (opts.compare) add(comparisonSection(ctx, opts.compare));
  add(notesSection(ctx));

  const missingIntrinsic = report.intrinsic ? "" : absent("Intrinsic metrics (per-stratum scores, confusion matrix, PR curve) are not in this report.");
  const name = ctx.x.names?.model ?? "model";
  const title = opts.title ?? `Evaluation report: ${name} (${report.report_id.slice(0, 15)})`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>${esc(title)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
${headerHtml(ctx, sections)}
${missingIntrinsic}${sections.map((s) => s.html).join("\n")}
<footer>Generated by gp report from a <code>${esc(report.format)}</code> document. All styles, charts and numbers are inline; this file works offline.</footer>
</main>
</body>
</html>
`;
}
